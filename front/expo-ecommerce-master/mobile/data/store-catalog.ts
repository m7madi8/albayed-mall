export function getCatalogProductCountsByDepartment(): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const dept of MALL_DEPARTMENTS) {
    counts[dept.name] = 0;
  }
  for (const product of STORE_CATALOG) {
    counts[product.category] = (counts[product.category] ?? 0) + 1;
  }
  return counts;
}

export function getCatalogProduct(productId: string) {
  return STORE_CATALOG.find((product) => product._id === productId) ?? null;
}

export function isCatalogProductId(productId: string) {
  return productId.startsWith("bayed-");
}
