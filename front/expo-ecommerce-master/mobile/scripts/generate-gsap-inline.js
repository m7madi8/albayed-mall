// Inlines the GSAP core build so the logo loader runs offline inside WebView / iframe.
// Run after upgrading gsap: npm run gen:gsap
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "node_modules/gsap/dist/gsap.min.js"), "utf8");
const target = path.join(root, "components/mall-logo-loader/gsap-source.ts");

fs.writeFileSync(
  target,
  `// Generated by scripts/generate-gsap-inline.js — do not edit.\nexport default ${JSON.stringify(source)};\n`
);
console.log(`Wrote ${path.relative(root, target)} (${(source.length / 1024).toFixed(1)} KB)`);
